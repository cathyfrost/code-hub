# 追加到 posts_corpus.csv
corpus_path = os.path.join("data", "raw", "posts_corpus.csv")

# 读取当前最大 id
max_id = 0
with open(corpus_path, "r", encoding="utf-8-sig") as f:
    reader = csv.DictReader(f)
    for row in reader:
        max_id = max(max_id, int(row["id"]))

# 追加
with open(corpus_path, "a", newline="", encoding="utf-8-sig") as f:
    writer = csv.writer(f)
    for i, content in enumerate(junk_samples, max_id + 1):
        writer.writerow([i, content, "", 1])

print(f"已追加 {len(junk_samples)} 条垃圾样本（id {max_id+1} ~ {max_id+len(junk_samples)}）")
print(f"保存到 {corpus_path}")

# 统计新的比例
tech = 0
junk = 0
with open(corpus_path, "r", encoding="utf-8-sig") as f:
    reader = csv.DictReader(f)
    for row in reader:
        if int(row["is_junk"]) == 1:
            junk += 1
        else:
            tech += 1
print(f"\n当前语料总计: {tech + junk} 条")
print(f"  技术帖: {tech}")
print(f"  垃圾帖: {junk}")
print(f"  垃圾占比: {junk / (tech + junk) * 100:.1f}%")